/** How much attention a launch battle draws, by section (#1–40 fights, 41–70 cheating, …). */
function launchHeat(n: number) {
  if (n <= 40) return 1.5;
  if (n <= 70) return 1.6;
  if (n <= 110) return 1.1;
  if (n <= 150) return 1.2;
  if (n <= 174) return 1.0;
  return 0.9;
}

