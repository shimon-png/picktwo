if (LAUNCH_A.length !== LAUNCH_BATTLES.length) throw new Error(`need ${LAUNCH_BATTLES.length} shares, got ${LAUNCH_A.length}`);

// Seeded RNG so the file is reproducible.
let s = 5000;
const rand = () => ((s = (s * 1103515245 + 12345) % 2147483648) / 2147483648);
const gauss = () => Math.sqrt(-2 * Math.log(rand() || 1e-9)) * Math.cos(2 * Math.PI * rand());

type Row = { id: string; a: number; heat: number };
const rows: Row[] = [
  ...LAUNCH_A.map((a, i) => ({ id: `seed_vb_${i + 1}`, a, heat: launchHeat(i + 1) })),
  ...Object.entries(OLD_A).map(([id, a]) => ({ id, a, heat: 0.55 })),
];
// Long-tailed popularity: a few battles take off, most get a handful.
const weights = rows.map((r) => r.heat * Math.exp(0.6 * gauss()));
const sum = weights.reduce((x, y) => x + y, 0);
const counts = weights.map((w) => Math.max(4, Math.round((w / sum) * TOTAL)));
let diff = TOTAL - counts.reduce((x, y) => x + y, 0);
for (let i = 0; diff !== 0; i = (i + 1) % counts.length) {
  if (diff > 0) { counts[i]++; diff--; } else if (counts[i] > 4) { counts[i]--; diff++; }
}

const tuples: string[] = [];
rows.forEach((r, i) => {
  const n = counts[i];
  let a = 0;
  for (let k = 0; k < n; k++) if (rand() * 100 < r.a) a++;
  tuples.push(`  ('${r.id}', ${a}, ${n - a})`);
});

const sql = `-- 5,000 seed votes over the seed battles (Alex, Nov 22 2026). Generated by scripts/gen-seed-votes.ts.
-- Anonymous (device 'seedvote_…', source 'seed'), no points, no reasons. Undo: DELETE FROM vote WHERE source = 'seed'; then recount.
CREATE TEMP TABLE seed_votes (id text, a int, b int);
--> statement-breakpoint
INSERT INTO seed_votes VALUES
${tuples.join(",\n")};
--> statement-breakpoint
INSERT INTO "vote" ("id", "battle_id", "device_id", "side", "dwell_ms", "source", "created_at")
SELECT 'sv_' || substr(md5(b.id || ':' || s.side || ':' || g), 1, 20), b.id, 'seedvote_' || substr(md5(b.id || ':' || s.side || ':' || g), 1, 16),
  s.side::"side", 2500 + floor(random() * 12000)::int,
  'seed',
  b.created_at + (power(random(), 1.6) * (least(now(), b.deadline) - b.created_at))
FROM seed_votes v
JOIN "battle" b ON b.id = v.id
CROSS JOIN LATERAL (VALUES ('A', v.a), ('B', v.b)) AS s(side, n)
CROSS JOIN LATERAL generate_series(1, s.n) AS g
WHERE NOT EXISTS (SELECT 1 FROM "vote" x WHERE x.source = 'seed' AND x.battle_id = b.id)
ON CONFLICT DO NOTHING;
--> statement-breakpoint
UPDATE "battle" b SET
  "votes_a" = (SELECT count(*) FROM "vote" v WHERE v.battle_id = b.id AND v.side = 'A'),
  "votes_b" = (SELECT count(*) FROM "vote" v WHERE v.battle_id = b.id AND v.side = 'B')
WHERE b.id IN (SELECT id FROM seed_votes);
--> statement-breakpoint
DROP TABLE seed_votes;
`;
writeFileSync("drizzle/0022_seed_votes.sql", sql);
