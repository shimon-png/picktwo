/**
 * Writes drizzle/0016_seed_launch_rewrite.sql (Alex, Nov 22 2026): the launch battles' options were rewritten
 * to sound like the poster (short labels, a casual aside or nothing), and contexts that repeated the title dropped.
 * Updates the rows migration 0014 created, by id, from scripts/launch-battles.data.ts.
 *
 *   npx tsx scripts/gen-launch-rewrite.ts
 */
import { writeFileSync } from "node:fs";
import { LAUNCH_BATTLES } from "./launch-battles.data";
import { isAbusive } from "../src/server/moderation";

const q = (s: string) => (s ? `'${s.replace(/'/g, "''")}'` : "NULL");
const errors: string[] = [];
LAUNCH_BATTLES.forEach(([, context, al, ad, bl, bd], i) => {
  if (context.length > 280) errors.push(`#${i + 1} context length`);
  if (!al || !bl || al.length > 60 || bl.length > 60) errors.push(`#${i + 1} label length`);
  if (ad.length > 140 || bd.length > 140) errors.push(`#${i + 1} description length`);
  if (al === bl) errors.push(`#${i + 1} same labels`);
  for (const t of [context, al, ad, bl, bd]) if (isAbusive(t)) errors.push(`#${i + 1} blocked word: ${t}`);
});
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

const battles = LAUNCH_BATTLES.map(([, c], i) => `  ('seed_vb_${i + 1}', ${c ? q(c) : "''"})`);
const options = LAUNCH_BATTLES.flatMap(([, , al, ad, bl, bd], i) => [
  `  ('seed_vo_${i + 1}_a', ${q(al)}, ${q(ad)})`,
  `  ('seed_vo_${i + 1}_b', ${q(bl)}, ${q(bd)})`,
]);
const sql = `-- Launch battles, options rewritten in the poster's voice (Alex, Nov 22 2026). Generated by scripts/gen-launch-rewrite.ts.
UPDATE "battle" b SET "context" = v.c, "updated_at" = now()
FROM (VALUES
${battles.join(",\n")}
) AS v(id, c)
WHERE b.id = v.id;
--> statement-breakpoint
UPDATE "option" o SET "label" = v.l, "description" = v.d
FROM (VALUES
${options.join(",\n")}
) AS v(id, l, d)
WHERE o.id = v.id;
`;
writeFileSync("drizzle/0016_seed_launch_rewrite.sql", sql);
console.log(`${LAUNCH_BATTLES.length} battles rewritten`);
