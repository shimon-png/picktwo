/**
 * A simulated email's leading letters, the part `suggestedHandle()` keeps (digits and dots after it drop):
 * "jessica.lee" → jessica, "achizhik" (a + surname) → achizhik, "airchi964" (two initials + bit of surname) → airchi,
 * "kmiller22" → kmiller, "katiewalsh" → katiewalsh, "jessm" → jessm.
 */
function emailName(): string {
  const f = pick(FIRST);
  const l = pick(LAST);
  const r = rand();
  const n =
    r < 0.35 ? f // jessica.lee@ / jessica92@
    : r < 0.55 ? f[0] + l // jmiller@ / achizhik@
    : r < 0.7 ? f + l[0] // jessicam@
    : r < 0.82 ? f + l // katiewalsh@
    : r < 0.92 ? f.slice(0, 2) + l.slice(0, 4) // airchi964@ style
    : f.slice(0, 4) + l[0]; // jessm@
  return n.slice(0, 10);
}

const ids = readFileSync(process.argv[2]!, "utf8").split(/\s+/).filter((x) => /^seed_[a-z]*u_\d+$/.test(x));
const used = new Set<string>();
const rows: string[] = [];
for (const id of ids) {
  if (rand() < 0.25) continue; // keeps the name they "picked themselves"
  let h = "";
  do h = `${emailName()}${1000 + Math.floor(rand() * 9000)}`;
  while (used.has(h));
  used.add(h);
  rows.push(`  ('${id}', '${h}')`);
}

const sql = `-- Seed posters look like real sign-ups (Alex, Nov 22 2026): ${rows.length} of ${ids.length} seed profiles get the
-- username sign-up suggests (email name + 4 digits); the rest keep their self-chosen names.
-- Generated by scripts/gen-seed-handles.ts. Skips a handle a real user already has.
UPDATE "user" u SET "handle" = v.h, "name" = v.h
FROM (VALUES
${rows.join(",\n")}
) AS v(id, h)
WHERE u.id = v.id AND NOT EXISTS (SELECT 1 FROM "user" x WHERE x.handle = v.h AND x.id <> u.id);
--> statement-breakpoint
-- Every undecided, visible seed battle runs a full 5 days from now (posted within the last few hours).
UPDATE "battle" b SET
  "status" = 'OPEN',
  "created_at" = now() - make_interval(mins => 5 + (abs(hashtext(b.id)) % 240)),
  "deadline" = now() - make_interval(mins => 5 + (abs(hashtext(b.id)) % 240)) + interval '120 hours',
  "closed_at" = NULL,
  "reminder_count" = 0,
  "last_reminder_at" = NULL,
  "updated_at" = now()
WHERE b.id LIKE 'seed\\_%'
  AND b.status IN ('OPEN', 'CLOSED')
  AND NOT EXISTS (SELECT 1 FROM "outcome" o WHERE o.battle_id = b.id)
  AND NOT EXISTS (SELECT 1 FROM "user" a WHERE a.id = b.author_id AND a.banned_at IS NOT NULL);
`;
writeFileSync("drizzle/0015_seed_handles_relaunch.sql", sql);
