/**
 * Writes drizzle/0014_seed_launch_battles.sql from scripts/launch-battles.data.ts.
 * Deterministic (seeded RNG), so re-running gives the same file. Checks lengths and the
 * profanity filter so every seed is something a real user could have posted.
 *
 *   npx tsx scripts/gen-launch-seeds.ts
 */
import { writeFileSync } from "node:fs";
import { LAUNCH_BATTLES } from "./launch-battles.data";
import { generateHandle } from "../src/lib/handles";
import { isAbusive } from "../src/server/moderation";
import { TITLE_MAX } from "../src/lib/constants";

function mulberry32(seed: number) {
  return () => {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = mulberry32(20261122);
const int = (lo: number, hi: number) => lo + Math.floor(rand() * (hi - lo + 1));
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const ALNUM = "abcdefghijkmnopqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789";
const slug = () => "v" + Array.from({ length: 7 }, () => ALNUM[int(0, ALNUM.length - 1)]).join("");

const errors: string[] = [];
const seenTitles = new Set<string>();
LAUNCH_BATTLES.forEach(([title, context, al, ad, bl, bd], i) => {
  const n = i + 1;
  if (title.length < 3 || title.length > TITLE_MAX) errors.push(`#${n} title length ${title.length}`);
  if (context.length > 280) errors.push(`#${n} context length`);
  if (al.length > 60 || bl.length > 60) errors.push(`#${n} label length`);
  if (ad.length > 140 || bd.length > 140) errors.push(`#${n} description length`);
  if (al === bl) errors.push(`#${n} same labels`);
  for (const t of [title, context, al, ad, bl, bd]) if (isAbusive(t)) errors.push(`#${n} blocked word: ${t}`);
  if (seenTitles.has(title)) errors.push(`#${n} duplicate title`);
  seenTitles.add(title);
});
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

// Posters: mostly one battle each, about 1 in 6 posts a second one (like real early users).
const handles: string[] = [];
const authorOf: number[] = [];
const taken = new Set<string>();
for (let i = 0; i < LAUNCH_BATTLES.length; i++) {
  if (handles.length > 10 && rand() < 0.16) {
    authorOf.push(int(0, handles.length - 1));
    continue;
  }
  let h = generateHandle({ rand });
  while (taken.has(h)) h = generateHandle({ rand });
  taken.add(h);
  handles.push(h);
  authorOf.push(handles.length - 1);
}

const users = handles.map((h, i) => `  ('seed_vu_${i + 1}', ${q(h)}, ${q(h)}, true, now(), '{}')`);
const battles = LAUNCH_BATTLES.map(([title, context], i) => {
  const ageMin = int(5, 2600); // posted within the last ~2 days
  const hoursLeft = int(70, 118); // under the 5-day cap
  return `  ('seed_vb_${i + 1}', '${slug()}', (SELECT id FROM "user" WHERE handle = ${q(handles[authorOf[i]!]!)}), ${q(title)}, ${q(context)}, 'other', '{}'::jsonb, now() + interval '${hoursLeft} hours', now() - interval '${ageMin} minutes')`;
});
const options = LAUNCH_BATTLES.flatMap(([, , al, ad, bl, bd], i) => [
  `  ('seed_vo_${i + 1}_a', 'seed_vb_${i + 1}', 'A', ${q(al)}, ${q(ad)}, NULL)`,
  `  ('seed_vo_${i + 1}_b', 'seed_vb_${i + 1}', 'B', ${q(bl)}, ${q(bd)}, NULL)`,
]);

const sql = `-- Launch seed battles (Alex, Nov 22 2026): ${LAUNCH_BATTLES.length} text battles in casual, real-post language
-- (couples fights, cheating/flirting, dating profiles + Hinge/Bumble prompts, weddings, in-laws, parenting, money, jobs),
-- inspired by Reddit AITA / relationship_advice / weddingshaming and TikTok debates.
-- Posted by ${handles.length} generated profiles. No fake votes. Generated by scripts/gen-launch-seeds.ts; idempotent.
INSERT INTO "user" ("id", "handle", "name", "is_adult_confirmed", "onboarded_at", "kid_ages") VALUES
${users.join(",\n")}
ON CONFLICT DO NOTHING;
--> statement-breakpoint
INSERT INTO "battle" ("id", "slug", "author_id", "title", "context", "category_id", "tags", "deadline", "created_at") VALUES
${battles.join(",\n")}
ON CONFLICT DO NOTHING;
--> statement-breakpoint
INSERT INTO "option" ("id", "battle_id", "side", "label", "description", "image_url")
SELECT v."id", v."battle_id", v."side"::side, v."label", v."description", v."image_url" FROM (VALUES
${options.join(",\n")}
) AS v("id", "battle_id", "side", "label", "description", "image_url")
WHERE EXISTS (SELECT 1 FROM "battle" b WHERE b.id = v."battle_id")
ON CONFLICT DO NOTHING;
`;
writeFileSync("drizzle/0014_seed_launch_battles.sql", sql);
console.log(`${LAUNCH_BATTLES.length} battles, ${handles.length} posters`);
